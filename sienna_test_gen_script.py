#!/usr/bin/env python3
import argparse
import os
import struct
from typing import List, Tuple

import numpy as np


# -----------------------------
# Utilities: float/int <-> hex
# -----------------------------
def float_to_hex(f):
    """Convert a float32 to an 8-character hex string (big-endian)."""
    return "".join(f"{b:02x}" for b in struct.pack(">f", np.float32(f)))


def hex_to_float(hex_str):
    """Convert an 8-character hex string to float32."""
    return struct.unpack(">f", bytes.fromhex(hex_str))[0]


def _is_float_like(v):
    return isinstance(v, (float, np.floating))


def _is_int_like(v):
    return isinstance(v, (int, np.integer))


# -----------------------------
# MIF writers
# -----------------------------
def write_mif_file(filename, data, width=32, depth=None):
    """
    Write data to a MIF (Memory Initialization File) format.

    Parameters:
    - filename: output file path
    - data: numpy array or list/iterable of values (float32 or int32)
    - width: bit width of each entry (default 32 for float32)
    - depth: number of entries (auto-calculated if None)
    """
    values = data.flatten() if isinstance(data, np.ndarray) else list(data)
    if depth is None:
        depth = len(values)

    with open(filename, "w") as f:
        # Header
        f.write(f"-- Memory Initialization File (.mif)\n")
        f.write(f"-- Generated by Sienna Pipeline Test Vector Generator\n\n")
        f.write(f"WIDTH={width};\n")
        f.write(f"DEPTH={depth};\n\n")
        f.write(f"ADDRESS_RADIX=UNS;\n")
        f.write(f"DATA_RADIX=HEX;\n\n")
        f.write(f"CONTENT BEGIN\n")

        # Data
        for addr, val in enumerate(values):
            if _is_float_like(val):
                hex_val = float_to_hex(val)
            elif _is_int_like(val):
                hex_val = f"{int(val) & 0xFFFFFFFF:08x}"
            else:
                # attempt cast
                try:
                    if isinstance(val, str) and val.startswith("0x"):
                        hex_val = f"{int(val, 16) & 0xFFFFFFFF:08x}"
                    else:
                        hex_val = float_to_hex(np.float32(val))
                except Exception:
                    raise TypeError(f"Unsupported value type at index {addr}: {type(val)}")
            f.write(f"    {addr} : {hex_val};\n")

        f.write(f"END;\n")


def write_config_mif_from_items(filename, items: List[Tuple[str, int | float, str]], width=32):
    """
    Write a config MIF from an ordered list of (name, value, vtype) tuples.

    items: list[ (name: str, value: int|float, vtype: 'int'|'float') ]
           Floats are encoded as IEEE-754 float32 (big-endian) hex.
           Ints are written as 32-bit hex.
    """
    depth = len(items)
    with open(filename, "w") as f:
        f.write(f"-- Test Configuration File (.mif)\n")
        f.write(f"-- Generated by Sienna Pipeline Test Vector Generator\n\n")
        f.write(f"WIDTH={width};\n")
        f.write(f"DEPTH={depth};\n\n")
        f.write(f"ADDRESS_RADIX=UNS;\n")
        f.write(f"DATA_RADIX=HEX;\n\n")
        f.write(f"CONTENT BEGIN\n")

        for addr, (name, val, vtype) in enumerate(items):
            if vtype == "float":
                hex_val = float_to_hex(np.float32(val))
                human = f"{float(val):.6g}"
            else:
                hex_val = f"{int(val) & 0xFFFFFFFF:08x}"
                human = f"{int(val)}"
            f.write(f"    {addr} : {hex_val};  -- {name} = {human}\n")

        f.write(f"END;\n")


# -----------------------------
# Activation helpers
# -----------------------------
def activation_to_code(activation_type):
    """
    Convert activation function name to 2-bit control code.

    Encoding:
    - 00: Linear/None
    - 01: ReLU
    - 10: Sigmoid
    - 11: Tanh
    """
    mapping = {
        "none": 0b00,
        "linear": 0b00,
        "relu": 0b01,
        "sigmoid": 0b10,
        "tanh": 0b11,
    }
    return mapping.get(activation_type.lower(), 0b01)


def apply_activation(x, activation_type="relu"):
    """Apply activation function element-wise."""
    if activation_type == "relu":
        return np.maximum(0, x)
    elif activation_type == "sigmoid":
        return 1 / (1 + np.exp(-np.clip(x, -500, 500)))
    elif activation_type == "tanh":
        return np.tanh(x)
    elif activation_type == "none":
        return x
    else:
        return x


# -----------------------------
# MaxPool & Dropout (golden)
# -----------------------------
def apply_maxpool_2d(
    input_matrix, pool_h=2, pool_w=2, stride_h=None, stride_w=None, padding=0
):
    """
    Apply 2D max pooling to input matrix.

    Parameters:
    - input_matrix: 2D numpy array (IN_ROWS x IN_COLS)
    - pool_h, pool_w: pooling window size
    - stride_h, stride_w: stride (defaults to pool size if None)
    - padding: zero padding around input; integer -> pad equally on both dims
               or ((top,bottom),(left,right)) tuple
    """
    if stride_h is None:
        stride_h = pool_h
    if stride_w is None:
        stride_w = pool_w

    # Add padding
    if padding is not None and (isinstance(padding, int) and padding > 0):
        input_matrix = np.pad(input_matrix, ((padding, padding), (padding, padding)),
                              mode="constant", constant_values=0)
    elif isinstance(padding, tuple):
        input_matrix = np.pad(input_matrix, padding, mode="constant", constant_values=0)

    in_h, in_w = input_matrix.shape
    out_h = (in_h - pool_h) // stride_h + 1
    out_w = (in_w - pool_w) // stride_w + 1

    output = np.zeros((out_h, out_w), dtype=np.float32)

    for i in range(out_h):
        for j in range(out_w):
            h_start = i * stride_h
            w_start = j * stride_w
            window = input_matrix[
                h_start: h_start + pool_h, w_start: w_start + pool_w
            ]
            output[i, j] = np.max(window)

    return output


def apply_dropout(x, dropout_p=0.5, training_mode=False, seed=None):
    """
    Apply dropout (for golden reference, we'll assume inference mode = no dropout).

    Parameters:
    - x: input array
    - dropout_p: dropout probability
    - training_mode: if True, randomly drop elements
    - seed: random seed
    """
    if training_mode:
        if seed is not None:
            np.random.seed(seed)
        mask = np.random.binomial(1, 1 - dropout_p, size=x.shape)
        return x * mask / (1 - dropout_p)
    else:
        # Inference mode - no dropout
        return x


